// init 解析字典 → 单字映射表 + 词组表(按首 rune 分组, 供位置扫描)。
var (
	charMap     map[rune]rune
	phraseMap   map[string]string
	phraseByLen map[int]map[string]struct{} // 按词长索引的繁词集合(最长优先探测)
	hasCJKKey   map[rune]struct{}           // 词组首字+单字 key 的并集(快速路径探测)
	initOnce    sync.Once
)

func build() {
	charMap = make(map[rune]rune, 4096)
	applyCharPairs(charPairs)
	applyCharPairs(openccCharPairs) // OpenCC 权威后写覆盖(手工集只兜 OpenCC 缺失的异体/两岸形态)
	phraseMap = make(map[string]string, 512)
	phraseByLen = make(map[int]map[string]struct{}, maxPhraseLen)
	applyPhrasePairs(phrasePairs)
	applyPhrasePairs(openccPhrasePairs) // 同上; TSPhrases 恒等保护词组在位
	hasCJKKey = make(map[rune]struct{}, len(charMap)+64)
	for k := range charMap {
		hasCJKKey[k] = struct{}{}
	}
	for p := range phraseMap {
		r, _ := utf8.DecodeRuneInString(p)
		hasCJKKey[r] = struct{}{}
	}
}

// applyCharPairs 解析「繁简,」紧凑对(严格两字符 CJK; byte 长度不校验, CJK 为
// 3-4 字节, rune 口径为权威)。后写覆盖先写。
func applyCharPairs(spec string) {
	for _, pair := range strings.Split(spec, ",") {
		pair = strings.TrimSpace(pair)
		r := []rune(pair)
		if len(r) == 2 && r[0] > 0x2e00 && r[1] > 0x2e00 && r[0] != r[1] {
			charMap[r[0]] = r[1]
		}
	}
}

// applyPhrasePairs 解析「繁|简,」词组对; 超过 maxPhraseLen 不进按长索引
// (扫描臂够不着), 仍入 phraseMap 保持语义一致。
func applyPhrasePairs(spec string) {
	for _, pair := range strings.Split(spec, ",") {
		pair = strings.TrimSpace(pair)
		kv := strings.SplitN(pair, "|", 2)
		if len(kv) != 2 || kv[0] == "" || kv[1] == "" {
			continue
		}
		phraseMap[kv[0]] = kv[1]
		n := utf8.RuneCountInString(kv[0])
		if n > maxPhraseLen {
			continue
		}
		if phraseByLen[n] == nil {
			phraseByLen[n] = make(map[string]struct{})
		}
		phraseByLen[n][kv[0]] = struct{}{}
	}
}

// Simplify 繁→简转换(词组最长优先, 后单字; 无命中零分配返回原串)。
// 线程安全: 只读表 init 构建后不再变更。
func Simplify(s string) string {
	initOnce.Do(build)
	if s == "" {
		return s
	}
	// 快速路径: 无任何潜在 key 首字 → 原样返回(ASCII 与简体文本零开销)。
	hit := false
	for i := 0; i < len(s); {
		c, sz := utf8.DecodeRuneInString(s[i:])
		if _, ok := hasCJKKey[c]; ok {
			hit = true
			break
		}
		i += sz
	}
	if !hit {
		return s
	}
	var b strings.Builder
	b.Grow(len(s) + 16)
	for i := 0; i < len(s); {
		c, sz := utf8.DecodeRuneInString(s[i:])
		// 词组臂: 以当前位置为起点, 词长从长到短探测。
		matched := ""
		if _, isPhraseStart := phraseStarts(c); isPhraseStart {
			for n := maxPhraseLen; n >= 2; n-- {
				if _, ok := phraseByLen[n]; !ok {
					continue
				}
				end := i
				chars := 0
				for chars < n && end < len(s) {
					_, z := utf8.DecodeRuneInString(s[end:])
					end += z
					chars++
				}
				if chars == n {
					if _, ok := phraseByLen[n][s[i:end]]; ok {
						matched = s[i:end]
						break
					}
				}
			}
		}
		if matched != "" {
			b.WriteString(phraseMap[matched])
			i += len(matched)
			continue
		}
		// 单字臂。
		if rep, ok := charMap[c]; ok {
			b.WriteRune(rep)
		} else {
			b.WriteString(s[i : i+sz])
		}
		i += sz
	}
	return b.String()
}

// phraseStarts 判断 rune 是否某词组首字。
func phraseStarts(c rune) (struct{}, bool) {
	_, ok := phraseHead[c]
	return struct{}{}, ok
}

var phraseHead map[rune]struct{}

func init() {
	initOnce.Do(build)
	phraseHead = make(map[rune]struct{}, 64)
	for p := range phraseMap {
		r, _ := utf8.DecodeRuneInString(p)
		phraseHead[r] = struct{}{}
	}
}
