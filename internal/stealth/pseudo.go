// synMap 词 → 伙伴词列表(init 装配一次; 读多写少, 装载后只读)。
var (
	synOnce      sync.Once
	synMap       map[string][]string
	synMaxRunes  int
	synPairTotal int
)

func synInit() {
	synOnce.Do(func() {
		m := make(map[string][]string, len(synonymPairs)*2)
		maxR := 0
		for _, p := range synonymPairs {
			i := strings.IndexByte(p, '|')
			if i <= 0 || i >= len(p)-1 {
				continue
			}
			a, b := p[:i], p[i+1:]
			ra, rb := []rune(a), []rune(b)
			if len(ra) < 2 || len(rb) < 2 { // 键至少 2 汉字(防单字成分误伤)
				continue
			}
			m[a] = append(m[a], b)
			if a != b {
				m[b] = append(m[b], a)
			}
			if len(ra) > maxR {
				maxR = len(ra)
			}
			if len(rb) > maxR {
				maxR = len(rb)
			}
			synPairTotal++
		}
		synMap = m
		synMaxRunes = maxR
	})
}

type pseudoMatch struct {
	start, end int // rune 下标区间
	word       string
}

// pseudoTokens 对 read 页文本节点做同义词替换(精确率钳制)。
// [R72-c 真虫修复] <title>(RCDATA) 内容豁免: title 是 TDK 引擎产出的 SEO 元数据,
// 修前同样被同义词改写(bookname/章节名命中词典即随机换词, request 种子下每次请求
// 标题不同)—— 搜索引擎侧标题不稳定 + 浏览器标签页标题漂移, 与 TDK/canonical 中的
// 原书名自相矛盾。修后与 obfTextNoise 同款守卫: 紧跟 noInsert 开标签的文本 token
// 不参与替换(title 无分节正文语境, 干扰句天然到不了)。
func pseudoTokens(toks []token, cfg Config, pc PageCtx) []token {
	synInit()
	if synPairTotal == 0 {
		return toks
	}
	r := pseudoRng(cfg, pc)
	rate := 0.05 + 0.20*r.Float64() // 目标替换率 ∈ [5%, 25%]

	// 第一遍: 收集全部命中(按 token 分组)。
	type tokMatches struct {
		idx int
		ms  []pseudoMatch
	}
	var per []tokMatches
	total := 0
	for idx := range toks {
		if toks[idx].kind != tokText || toks[idx].data == "" {
			continue
		}
		if idx > 0 && toks[idx-1].noInsert {
			continue // title(RCDATA) 内容逐字节不动
		}
		ms := pseudoFind(toks[idx].data)
		if len(ms) > 0 {
			per = append(per, tokMatches{idx: idx, ms: ms})
			total += len(ms)
		}
	}
	if total == 0 {
		return toks
	}
	k := int(rate * float64(total))
	if k == 0 && total >= 8 {
		k = 1
	}
	if k > total {
		k = total
	}

	// 第二遍: 顺序超几何抽样, 恰好替换 k 处。
	selected := 0
	seen := 0
	for ti := range per {
		tm := &per[ti]
		data := []rune(toks[tm.idx].data)
		var repl []pseudoMatch
		for _, m := range tm.ms {
			remain := k - selected
			left := total - seen
			if left <= 0 {
				break
			}
			if remain > 0 && (remain == left || r.Float64() < float64(remain)/float64(left)) {
				partners := synMap[m.word]
				w := partners[r.Intn(len(partners))]
				copyRunes := make([]rune, 0, m.end-m.start)
				copyRunes = append(copyRunes, []rune(w)...)
				repl = append(repl, pseudoMatch{start: m.start, end: m.end, word: string(copyRunes)})
				selected++
			}
			seen++
		}
		if len(repl) > 0 {
			// 从后往前替换, 保持 rune 下标有效。
			for i := len(repl) - 1; i >= 0; i-- {
				m := repl[i]
				out := make([]rune, 0, len(data))
				out = append(out, data[:m.start]...)
				out = append(out, []rune(m.word)...)
				out = append(out, data[m.end:]...)
				data = out
			}
			toks[tm.idx].data = string(data)
		}
	}
	return toks
}

// pseudoFind 文本内 longest-match-first 命中收集(不重叠, 从左到右)。
func pseudoFind(s string) []pseudoMatch {
	runes := []rune(s)
	var ms []pseudoMatch
	i := 0
	for i < len(runes) {
		matched := false
		for l := synMaxRunes; l >= 2; l-- {
			if i+l > len(runes) {
				continue
			}
			key := string(runes[i : i+l])
			if partners, ok := synMap[key]; ok && len(partners) > 0 {
				ms = append(ms, pseudoMatch{start: i, end: i + l, word: key})
				i += l
				matched = true
				break
			}
		}
		if !matched {
			i++
		}
	}
	return ms
}
